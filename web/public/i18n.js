let LANG = "en";
try {
  const saved = localStorage.getItem("ekomino-lang");
  LANG = saved || ((navigator.language || "").toLowerCase().startsWith("tr") ? "tr" : "en");
} catch {}
if (!I18N[LANG]) LANG = "en";

function t(key, vars = {}) {
  let s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

function applyStaticTexts() {
  document.documentElement.lang = LANG;
  document.title = LANG === "tr" ? "Ekomino İK Paneli" : "Ekomino HR Panel";
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  document.querySelectorAll("[data-lang]").forEach((b) => b.classList.toggle("active", b.dataset.lang === LANG));
}

function setLang(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  try { localStorage.setItem("ekomino-lang", lang); } catch {}
  applyStaticTexts();
  document.dispatchEvent(new Event("langchange"));
}
